/**
 * Export text-only DML for trip (+ optional live note/plan_item/trip_link).
 * Excludes content_blob / trip_content_file / image binaries.
 *
 * Usage: node content/scripts/export-text-dml.mjs [out.sql]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const PACK = path.join(ROOT, 'content/trips/eu2026')
const OUT =
  process.argv[2] ||
  path.join(ROOT, 'db/dml/20261009_text_snapshot.sql')

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`
}

function loadJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

function loadEnvDatabaseUrl() {
  const envPath = path.join(ROOT, '.env')
  if (!fs.existsSync(envPath)) return process.env.DATABASE_URL || ''
  const text = fs.readFileSync(envPath, 'utf8')
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*DATABASE_URL\s*=\s*(.+)\s*$/)
    if (m) {
      let v = m[1].trim()
      if (
        (v.startsWith('"') && v.endsWith('"')) ||
        (v.startsWith("'") && v.endsWith("'"))
      ) {
        v = v.slice(1, -1)
      }
      return v
    }
  }
  return process.env.DATABASE_URL || ''
}

const meta = loadJson(path.join(PACK, 'trip.json'))
const itinerary = loadJson(path.join(PACK, 'itinerary.json'))
const sites = loadJson(path.join(PACK, 'sites.json'))
const assets = fs.existsSync(path.join(PACK, 'assets.json'))
  ? loadJson(path.join(PACK, 'assets.json'))
  : {}
const manifest = fs.existsSync(path.join(PACK, 'manifest.json'))
  ? loadJson(path.join(PACK, 'manifest.json'))
  : {}

const tripId = meta.id
const doc = { itinerary, sites, assets }

const lines = []
lines.push('-- Text-only snapshot generated by content/scripts/export-text-dml.mjs')
lines.push(`-- Generated: ${new Date().toISOString()}`)
lines.push('-- Includes: trip (+ trip_document). Optional: note, plan_item, trip_link from live DB.')
lines.push('-- Excludes: content_blob, trip_content_file, image binaries.')
lines.push('')
lines.push('BEGIN;')
lines.push('')
lines.push(`-- trip ${meta.slug}`)
lines.push(`INSERT INTO trip (
  id, slug, title, start_date, end_date, status,
  content_version, trip_document, record_status,
  last_modified_on
) VALUES (
  ${sqlString(tripId)}::uuid,
  ${sqlString(meta.slug || 'eu2026')},
  ${sqlString(meta.title || itinerary.title || 'EU2026')},
  ${sqlString(meta.start_date)}::date,
  ${sqlString(meta.end_date)}::date,
  ${sqlString(meta.status || 'active')},
  ${sqlString(manifest.version || '1')},
  ${sqlJson(doc)},
  ${sqlString(meta.record_status || 'active')},
  now()
)
ON CONFLICT (id) DO UPDATE SET
  slug = EXCLUDED.slug,
  title = EXCLUDED.title,
  start_date = EXCLUDED.start_date,
  end_date = EXCLUDED.end_date,
  status = EXCLUDED.status,
  content_version = EXCLUDED.content_version,
  trip_document = EXCLUDED.trip_document,
  record_status = EXCLUDED.record_status,
  last_modified_on = now();
`)

const databaseUrl = loadEnvDatabaseUrl()
let liveCounts = { note: 0, plan_item: 0, trip_link: 0 }

if (databaseUrl) {
  const py = `
import json, os, sys
try:
    import psycopg
except ImportError:
    print(json.dumps({"ok": False, "error": "psycopg missing"}))
    sys.exit(0)
url = os.environ["DATABASE_URL"]
trip_id = os.environ["TRIP_ID"]
out = {"ok": True, "note": [], "plan_item": [], "trip_link": []}
try:
    with psycopg.connect(url) as conn:
        with conn.cursor() as cur:
            for table, cols in [
                ("note", "id, trip_id, day_id, stop_id, body, record_status, created_by, created_on, created_on_device, last_modified_by, last_modified_on, last_modified_on_device"),
                ("plan_item", "id, trip_id, site_id, day_id, kind, title, body, done, sort_order, record_status, created_by, created_on, created_on_device, last_modified_by, last_modified_on, last_modified_on_device"),
                ("trip_link", "id, trip_id, kind, label, payload, day_id, record_status, created_by, created_on, created_on_device, last_modified_by, last_modified_on, last_modified_on_device"),
            ]:
                cur.execute(f"SELECT {cols} FROM {table} WHERE trip_id = %s", (trip_id,))
                names = [d.name for d in cur.description]
                for row in cur.fetchall():
                    item = {}
                    for n, v in zip(names, row):
                        if hasattr(v, "isoformat"):
                            item[n] = v.isoformat()
                        elif isinstance(v, memoryview):
                            item[n] = bytes(v).hex()
                        else:
                            item[n] = v
                    out[table].append(item)
    print(json.dumps(out, default=str))
except Exception as e:
    print(json.dumps({"ok": False, "error": str(e)}))
`
  const result = spawnSync('python', ['-c', py], {
    env: { ...process.env, DATABASE_URL: databaseUrl, TRIP_ID: tripId },
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
  if (result.status === 0 && result.stdout.trim()) {
    try {
      const live = JSON.parse(result.stdout.trim().split(/\r?\n/).pop())
      if (live.ok) {
        for (const row of live.note || []) {
          liveCounts.note++
          lines.push(`INSERT INTO note (
  id, trip_id, day_id, stop_id, body, record_status,
  created_by, created_on, created_on_device,
  last_modified_by, last_modified_on, last_modified_on_device
) VALUES (
  ${sqlString(row.id)}::uuid,
  ${sqlString(row.trip_id)}::uuid,
  ${sqlString(row.day_id)},
  ${sqlString(row.stop_id)},
  ${sqlString(row.body ?? '')},
  ${sqlString(row.record_status || 'active')},
  ${sqlString(row.created_by)},
  ${row.created_on ? sqlString(row.created_on) + '::timestamptz' : 'now()'},
  ${sqlString(row.created_on_device)},
  ${sqlString(row.last_modified_by)},
  ${row.last_modified_on ? sqlString(row.last_modified_on) + '::timestamptz' : 'now()'},
  ${sqlString(row.last_modified_on_device)}
)
ON CONFLICT (id) DO UPDATE SET
  day_id = EXCLUDED.day_id,
  stop_id = EXCLUDED.stop_id,
  body = EXCLUDED.body,
  record_status = EXCLUDED.record_status,
  last_modified_by = EXCLUDED.last_modified_by,
  last_modified_on = EXCLUDED.last_modified_on,
  last_modified_on_device = EXCLUDED.last_modified_on_device;
`)
        }
        for (const row of live.plan_item || []) {
          liveCounts.plan_item++
          lines.push(`INSERT INTO plan_item (
  id, trip_id, site_id, day_id, kind, title, body, done, sort_order, record_status,
  created_by, created_on, created_on_device,
  last_modified_by, last_modified_on, last_modified_on_device
) VALUES (
  ${sqlString(row.id)}::uuid,
  ${sqlString(row.trip_id)}::uuid,
  ${sqlString(row.site_id)},
  ${sqlString(row.day_id)},
  ${sqlString(row.kind || 'todo')},
  ${sqlString(row.title ?? '')},
  ${sqlString(row.body ?? '')},
  ${row.done ? 'TRUE' : 'FALSE'},
  ${Number(row.sort_order) || 0},
  ${sqlString(row.record_status || 'active')},
  ${sqlString(row.created_by)},
  ${row.created_on ? sqlString(row.created_on) + '::timestamptz' : 'now()'},
  ${sqlString(row.created_on_device)},
  ${sqlString(row.last_modified_by)},
  ${row.last_modified_on ? sqlString(row.last_modified_on) + '::timestamptz' : 'now()'},
  ${sqlString(row.last_modified_on_device)}
)
ON CONFLICT (id) DO UPDATE SET
  site_id = EXCLUDED.site_id,
  day_id = EXCLUDED.day_id,
  kind = EXCLUDED.kind,
  title = EXCLUDED.title,
  body = EXCLUDED.body,
  done = EXCLUDED.done,
  sort_order = EXCLUDED.sort_order,
  record_status = EXCLUDED.record_status,
  last_modified_by = EXCLUDED.last_modified_by,
  last_modified_on = EXCLUDED.last_modified_on,
  last_modified_on_device = EXCLUDED.last_modified_on_device;
`)
        }
        for (const row of live.trip_link || []) {
          liveCounts.trip_link++
          lines.push(`INSERT INTO trip_link (
  id, trip_id, kind, label, payload, day_id, record_status,
  created_by, created_on, created_on_device,
  last_modified_by, last_modified_on, last_modified_on_device
) VALUES (
  ${sqlString(row.id)}::uuid,
  ${sqlString(row.trip_id)}::uuid,
  ${sqlString(row.kind)},
  ${sqlString(row.label)},
  ${sqlJson(row.payload ?? {})},
  ${sqlString(row.day_id)},
  ${sqlString(row.record_status || 'active')},
  ${sqlString(row.created_by)},
  ${row.created_on ? sqlString(row.created_on) + '::timestamptz' : 'now()'},
  ${sqlString(row.created_on_device)},
  ${sqlString(row.last_modified_by)},
  ${row.last_modified_on ? sqlString(row.last_modified_on) + '::timestamptz' : 'now()'},
  ${sqlString(row.last_modified_on_device)}
)
ON CONFLICT (id) DO UPDATE SET
  kind = EXCLUDED.kind,
  label = EXCLUDED.label,
  payload = EXCLUDED.payload,
  day_id = EXCLUDED.day_id,
  record_status = EXCLUDED.record_status,
  last_modified_by = EXCLUDED.last_modified_by,
  last_modified_on = EXCLUDED.last_modified_on,
  last_modified_on_device = EXCLUDED.last_modified_on_device;
`)
        }
      } else {
        lines.push(`-- Live DB dump skipped: ${live.error || 'unknown error'}`)
      }
    } catch (e) {
      lines.push(`-- Live DB dump parse failed: ${e.message}`)
    }
  } else {
    lines.push(
      `-- Live DB dump skipped: ${(result.stderr || result.stdout || 'no response').trim().slice(0, 200)}`,
    )
  }
} else {
  lines.push('-- DATABASE_URL not set; skipped note / plan_item / trip_link.')
}

lines.push('COMMIT;')
lines.push('')

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, lines.join('\n'), 'utf8')
console.log(
  JSON.stringify(
    {
      out: path.relative(ROOT, OUT).replace(/\\/g, '/'),
      tripId,
      sites: sites.length,
      liveCounts,
      bytes: fs.statSync(OUT).size,
    },
    null,
    2,
  ),
)
